import numpy as np 

#create float array using zero 
array_1 = np.zeros(5)

#create integer array using zero 
array_2 = np.zeros(5,dtype=int)

print(array_1)
print(array_2)

#create float array using ones
array_3 = np.ones(10)

#create integer array using ones
array_4 = np.ones(7,dtype=int)

#create 2d array using ones (float)
array_5 = np.ones([3,5])

print(array_3)
print(array_4)
print(array_5)